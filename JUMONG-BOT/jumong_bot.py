class BaleError(Exception):
    def __init__(self, description, code=None):
        super().__init__(description)
        self.code = code


class BaleClient:
    RETRY_CODES = (429, 500, 502, 503, 504)

    def __init__(self, token, base=API_BASE, retries=3):
        self.token = token
        self.base = base
        self.retries = retries
        self.sleep = time.sleep

    def call(self, method, params=None, timeout=15, retries=None):
        url = "%s%s/%s" % (self.base, self.token, method)
        body = json.dumps(params or {}, ensure_ascii=False).encode("utf-8")
        attempts = self.retries if retries is None else retries
        last = None
        for i in range(max(1, attempts)):
            delay = 1.5 * (i + 1)
            try:
                req = urllib.request.Request(
                    url, data=body, headers={"Content-Type": "application/json"}
                )
                with urllib.request.urlopen(req, timeout=timeout) as resp:
                    data = json.loads(resp.read().decode("utf-8"))
            except urllib.error.HTTPError as e:
                try:
                    data = json.loads(e.read().decode("utf-8"))
                except Exception:
                    data = {}
                desc = data.get("description") or ("HTTP %s" % e.code)
                last = BaleError(desc, e.code)
                if e.code in self.RETRY_CODES and i < attempts - 1:
                    retry_after = (data.get("parameters") or {}).get("retry_after")
                    self.sleep(min(float(retry_after or delay), 30))
                    continue
                raise last
            except (urllib.error.URLError, socket.timeout, TimeoutError,
                    ConnectionError, OSError, ValueError) as e:
                last = BaleError("network error: %s" % e, None)
                if i < attempts - 1:
                    self.sleep(delay)
                    continue
                raise last
            if isinstance(data, dict) and data.get("ok"):
                return data.get("result")
            code = data.get("error_code") if isinstance(data, dict) else None
            desc = (data.get("description") if isinstance(data, dict) else None) or "unknown API error"
            raise BaleError(desc, code)
        raise last or BaleError("unknown failure")


