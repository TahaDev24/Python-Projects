class FakeClient:
    def __init__(self):
        self.calls = []
        self.next_id = 100
        self.fail_edit = None   # پیام خطای ویرایش
        self.fail_photo = False

    def call(self, method, params=None, timeout=15, retries=None):
        params = params or {}
        self.calls.append((method, params))
        if method == "editMessageText" and self.fail_edit:
            raise BaleError(self.fail_edit, 400)
        if method == "sendPhoto" and self.fail_photo:
            raise BaleError("bad photo", 400)
        if method in ("sendMessage", "sendPhoto"):
            self.next_id += 1
            return {"message_id": self.next_id}
        return True


