def handle_message(client, msg):
    chat = msg.get("chat") or {}
    chat_id = chat.get("id")
    if chat_id is None or chat.get("type", "private") != "private":
        return
    sender = msg.get("from") or {}
    name = sender.get("first_name", "")
    text = (msg.get("text") or "").strip()
    cmd = text.split()[0].split("@")[0].lower() if text.startswith("/") else ""
    STATE.pop(chat_id, None)
    if cmd == "/start":
        photo = IMAGES.get("welcome")
        if photo:
            try:
                client.call("sendPhoto", {"chat_id": chat_id, "photo": photo, "caption": "👑 قلمرو گوگوریو"}, retries=1)
            except BaleError as e:
                log.info("ارسال تصویر ممکن نشد؛ ادامه به‌صورت متنی (%s)", e)
        scr = screen_main(name)
    elif cmd in ("/menu", "/help"):
        scr = screen_main(name)
    else:
        main_text, kb = screen_main(name)
        scr = ("برای گشتن در قلمرو از دکمه‌های زیر استفاده کن.\n\n" + main_text, kb)
    send_screen(client, chat_id, scr[0], scr[1])


def handle_callback(client, cq):
    cb_id = cq.get("id")
    msg = cq.get("message") or {}
    chat_id = (msg.get("chat") or {}).get("id")
    message_id = msg.get("message_id")
    user = cq.get("from") or {}
    uid = user.get("id", chat_id)
    if chat_id is None:
        answer_callback(client, cb_id)
        return
    text, kb, toast = route(chat_id, uid, user.get("first_name", ""), cq.get("data", ""))
    answer_callback(client, cb_id, toast)   # دکمه همیشه آزاد می‌شود
    send_screen(client, chat_id, text, kb, message_id)


def handle_update(client, update):
    try:
        if update.get("callback_query"):
            handle_callback(client, update["callback_query"])
        elif update.get("message"):
            handle_message(client, update["message"])
    except Exception:
        log.exception("خطا در پردازش آپدیت")


def poll_forever(client):
    try:
        client.call("deleteWebhook", {}, retries=2)   # وبهوک فعال، getUpdates را مسدود می‌کند
    except BaleError as e:
        log.info("deleteWebhook: %s", e)
    offset = None
    backoff = 1
    log.info("ربات آماده است و منتظر پیام می‌ماند. (توقف: Ctrl+C)")
    while True:
        params = {"timeout": 25, "limit": 50}
        if offset is not None:
            params["offset"] = offset
        try:
            updates = client.call("getUpdates", params, timeout=40, retries=1) or []
            backoff = 1
        except BaleError as e:
            if e.code in (401, 403, 404):
                log.error("توکن نامعتبر است یا دسترسی ندارد (%s). برنامه متوقف شد.", e)
                return 3
            log.warning("خطا در دریافت آپدیت (%s)؛ تلاش دوباره پس از %s ثانیه", e, backoff)
            time.sleep(backoff)
            backoff = min(backoff * 2, 60)
            continue
        for u in updates:
            offset = max(offset or 0, u.get("update_id", 0) + 1)
            handle_update(client, u)


