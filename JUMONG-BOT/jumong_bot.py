def war_action(chat_id, uid, st, step, arg):
    if step != st["step"]:
        return None, "این مرحله قدیمی است."
    try:
        i = int(arg)
    except ValueError:
        return None, "گزینه‌ی نامعتبر."
    if step < len(WAR_STAGES):
        choices = WAR_STAGES[step][1]
        if not 0 <= i < len(choices):
            return None, "گزینه‌ی نامعتبر."
        _, effects, result = choices[i]
        for k, v in effects.items():
            st["stats"][k] += v
        st["stats"] = war_clamp(st["stats"])
        st["step"] += 1
        return _war_screen(st, result), None
    forms = WAR_FINAL[1]
    if not 0 <= i < len(forms):
        return None, "گزینه‌ی نامعتبر."
    total, bonus, title, text = war_ending(st["stats"], forms[i][1])
    STATE.pop(chat_id, None)
    new = _score_store().update(uid, "war", total)
    msg = "⚔️ پایان نبرد\n%s\n%s\n%s\n\n%s\nامتیاز نهایی: %s%s%s" % (
        DIV, title, text, _war_stats(st["stats"]), fa(total),
        " (پاداش آرایش: %s)" % fa(bonus), "\n🌟 رکورد جدید!" if new else "")
    return (msg, final_kb("war")), None


