class ScoreStore:
    """رکورد هر بازی به‌ازای شناسه‌ی عددی کاربر. اگر نوشتن در فایل ممکن نباشد، فقط در حافظه می‌ماند."""

    def __init__(self, path):
        self.path = path
        self.lock = threading.Lock()
        self.data = {}
        self.persist = True
        try:
            with open(path, "r", encoding="utf-8") as f:
                loaded = json.load(f)
            if isinstance(loaded, dict):
                self.data = loaded
        except FileNotFoundError:
            pass
        except Exception as e:
            log.warning("خواندن رکوردها ممکن نشد (%s)؛ از حافظه استفاده می‌شود.", e)

    def best(self, uid, game):
        return (self.data.get(str(uid)) or {}).get(game)

    def all_for(self, uid):
        return dict(self.data.get(str(uid)) or {})

    def update(self, uid, game, value):
        """اگر value رکورد جدید باشد True برمی‌گرداند."""
        with self.lock:
            rec = self.data.setdefault(str(uid), {})
            old = rec.get(game)
            if old is not None and value <= old:
                return False
            rec[game] = value
            self._save()
            return True

    def _save(self):
        if not self.persist:
            return
        try:
            folder = os.path.dirname(self.path) or "."
            fd, tmp = tempfile.mkstemp(dir=folder, suffix=".tmp")
            with os.fdopen(fd, "w", encoding="utf-8") as f:
                json.dump(self.data, f, ensure_ascii=False)
            os.replace(tmp, self.path)
        except Exception as e:
            self.persist = False
            log.warning("ذخیره‌ی رکورد در فایل ممکن نشد (%s)؛ فقط در حافظه نگه داشته می‌شود.", e)


