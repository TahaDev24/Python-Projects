def archer_p(base, wind, opt):
    if opt == "d":
        mod = (0.15, 0.0, -0.2)[wind]
    elif opt == "c":
        mod = (-0.05, 0.1, 0.15)[wind]
    else:
        mod = (0.05, 0.05, 0.0)[wind]
    return min(0.95, max(0.05, base + mod))


