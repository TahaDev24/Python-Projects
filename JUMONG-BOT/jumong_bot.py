def _war_stats(stats):
    return "\n".join("%s %s %s/۱۰" % (WAR_LABELS[k], bar(v), fa(v)) for k, v in stats.items())


def _war_screen(st, prev):
    step = st["step"]
    if step < len(WAR_STAGES):
        q, choices = WAR_STAGES[step]
        labels = [c[0] for c in choices]
