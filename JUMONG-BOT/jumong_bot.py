def route(chat_id, uid, name, data):
    """خروجی: (text, keyboard, toast). هیچ‌وقت exception نمی‌دهد."""
    try:
        return _route(chat_id, uid, name, data)
    except Exception:
        log.exception("خطا در مسیریابی: %r", data)
        text, kb = screen_main(name)
        return "یک مشکل کوچک پیش آمد. به منوی اصلی برگشتیم.\n\n" + text, kb, "خطای موقت"


def _route(chat_id, uid, name, data):
    if len(STATE) + len(SESSION) > 300:
        purge_state()
    data = (data or "")[:64]
    parts = data.split(":")
    head = parts[0]

    # بازی‌های در جریان فقط با callbackهای «x:» و «gs:» ادامه می‌یابند؛ هر مسیر دیگری وضعیت را پاک می‌کند.
    if head not in ("x", "gs"):
        STATE.pop(chat_id, None)

    def done(scr, toast=None):
        return scr[0], scr[1], toast

    if data == "m" or data == "":
        return done(screen_main(name))
    if head == "c" and len(parts) == 2 and parts[1] in CATS:
        if parts[1] == "won":
            return done(screen_won(chat_id, uid))
        return done(screen_cat(parts[1]))
    if head == "p" and len(parts) == 3 and parts[1] in CATS:
        items = CATS[parts[1]]["items"]
        if parts[2].isdigit() and int(parts[2]) < len(items):
            return done(screen_item(parts[1], int(parts[2])))
        return done(screen_cat(parts[1]), "صفحه‌ی نامعتبر")
    if head == "r" and len(parts) == 2 and parts[1] in POOLS:
        return done(screen_random(parts[1]))
    if data == "rep":
        return done(screen_report())
    if data == "fun":
        return done(screen_fun())
    if data == "won":
        return done(screen_won(chat_id, uid))
    if data == "doors":
        return done(screen_doors(chat_id))
    if head == "door" and len(parts) == 2 and parts[1] in DOORS:
        return done(screen_door(chat_id, parts[1]))
    if data == "crow":
        return done(screen_crow(chat_id))
    if data == "creator":
        return done(screen_creator())
    if data == "abt":
        return done(screen_about())
    if data == "feather":
        return done(screen_feather())
    if data == "sc":
        return done(screen_scores(uid))
    if head == "g" and len(parts) == 2 and parts[1] in GAME_INTRO:
        return done(screen_game_intro(parts[1]))
    if head == "gs" and len(parts) == 2 and parts[1] in GAME_INTRO:
        game = parts[1]
        if game in MCQ:
            return done(mcq_start(chat_id, game)[0])
        return done(archer_start(chat_id) if game == "archer" else war_start(chat_id))
    if head == "x" and len(parts) == 4:
        st = STATE.get(chat_id)
        if not st or st.get("game") != parts[1]:
            return done(screen_fun(), "این بازی دیگر فعال نیست.")
        if not parts[2].isdigit():
            return done(_current_screen(st), "گزینه‌ی نامعتبر")
        step = int(parts[2])
        st["t"] = time.time()
        fn = {"archer": archer_action, "war": war_action}.get(st["game"], mcq_action)
        res, toast = fn(chat_id, uid, st, step, parts[3])
        if res is None:
            return done(_current_screen(st), toast)
        return done(res, toast)
    return done(screen_main(name), "گزینه‌ی نامعتبر")


def _current_screen(st):
    g = st["game"]
    if g == "archer":
        return _archer_screen(st, "")
    if g == "war":
        return _war_screen(st, "")
    return _mcq_question_screen(st)


